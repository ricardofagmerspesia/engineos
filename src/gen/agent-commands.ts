// `engineos gen agent-commands` — one slash-command entrypoint per agent canonical
// name AND per alias, so an agent is invocable with `/<name>` or `/<alias>`. Port of
// scripts/gen-agent-commands.sh, which is now a shim over this.
//
// CUSTOMIZATION IS PRESERVED, and that is the whole reason this generator is not a
// plain overwrite: every file it writes carries MARKER. A file WITH the marker is
// refreshed; a file WITHOUT it is hand-customized and left alone, and a stale file
// is deleted only when it still carries the marker. Deleting the marker line is
// therefore the documented way to adopt a command permanently.
//
// The marker text, the preserve rule and every line printed here are public surface
// (docs/COMPATIBILITY.md): the marker decides which committed files survive a run,
// so changing its bytes would orphan every command generated before the change.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Io } from '../io';
import { frontmatterAlias, frontmatterValue } from './frontmatter';

const EXIT_OK = 0;
const EXIT_FAILURE = 1;

// Byte-for-byte the bash MARKER, em dash included. Named as the generator's own
// path because that is still how an operator runs it.
export const MARKER =
  '<!-- @generated by scripts/gen-agent-commands.sh — do not edit. To customize this command, delete this line and the generator will preserve your changes. -->';

export interface GenerateCommandsResult {
  generated: number;
  preserved: number;
  removed: number;
  keptOrphan: number;
}

// One run's mutable state, so the writers below stay two-argument functions.
interface Run {
  outDir: string;
  // The invoke names this run owns. Everything else in outDir is stale.
  expected: Set<string>;
  counts: GenerateCommandsResult;
  io: Io;
}

interface CommandSpec {
  invoke: string;
  agent: string;
  alias: string;
  desc: string;
}

export function generateAgentCommands(root: string, io: Io): number {
  const agentsDir = join(root, 'agents');
  const outDir = join(root, 'commands', 'agents');

  if (!isDirectory(agentsDir)) {
    io.err(`No agents dir at ${agentsDir}\n`);
    return EXIT_FAILURE;
  }
  mkdirSync(outDir, { recursive: true });

  const run: Run = { outDir, expected: new Set<string>(), counts: { generated: 0, preserved: 0, removed: 0, keptOrphan: 0 }, io };

  for (const file of agentFiles(agentsDir)) {
    const text = readOrEmpty(file);
    const name = frontmatterValue(text, 'name');
    if (name === '') {
      io.err(`skip (no name): ${file}\n`);
      continue;
    }
    const alias = frontmatterAlias(text);
    const desc = `Invoke the ${name} agent${alias === '' ? '' : ` (alias ${alias})`}.`;

    emit(run, { invoke: name, agent: name, alias, desc });
    // An agent whose alias equals its name gets one command, not two identical ones.
    if (alias !== '' && alias !== name) emit(run, { invoke: alias, agent: name, alias, desc });
  }

  prune(run);

  const { generated, preserved, removed, keptOrphan } = run.counts;
  io.out(`Done in ${outDir} — generated: ${generated}, preserved: ${preserved}, removed stale: ${removed}, kept orphaned customized: ${keptOrphan}\n`);
  return EXIT_OK;
}

// -------------------------------------------------------------------- helpers

function emit(run: Run, spec: CommandSpec): void {
  run.expected.add(spec.invoke);
  const out = join(run.outDir, `${spec.invoke}.md`);

  if (existsSync(out) && !isGenerated(out)) {
    run.io.err(`preserved (customized): ${spec.invoke}.md\n`);
    run.counts.preserved += 1;
    return;
  }

  writeFileSync(out, commandBody(spec));
  run.counts.generated += 1;
}

// Stale entrypoints go, but only ones this generator wrote. A customized orphan is
// reported and kept: the operator deleted the marker to say "this file is mine now",
// and an agent rename is not consent to discard it.
function prune(run: Run): void {
  for (const file of markdownNames(run.outDir)) {
    const base = file.slice(0, -'.md'.length);
    if (run.expected.has(base)) continue;
    const out = join(run.outDir, file);
    if (isGenerated(out)) {
      rmSync(out, { force: true });
      run.io.err(`removed stale: ${base}.md\n`);
      run.counts.removed += 1;
    } else {
      run.io.err(`kept orphaned customized (agent removed/renamed?): ${base}.md\n`);
      run.counts.keptOrphan += 1;
    }
  }
}

function commandBody(spec: CommandSpec): string {
  const { agent, alias, desc } = spec;
  const aliasSuffix = alias === '' ? '' : ` (alias \`${alias}\`)`;
  return `---
description: ${desc}
argument-hint: [task or question for the agent]
allowed-tools: Task
---
${MARKER}

Dispatch the \`${agent}\` agent${aliasSuffix} via the Task tool, passing
\`$ARGUMENTS\` as its prompt. If \`$ARGUMENTS\` is empty, ask the user what they
want the agent to do before dispatching.

The agent follows its own mode and output rules (it self-infers AUDIT vs
IMPLEMENT where applicable). Relay its report back verbatim; do not re-do its
work yourself.
`;
}

// Safe to overwrite or remove. An unreadable file answers "not generated", the same
// way the bash `grep -qF` failed closed — the cautious side of this question keeps a
// file, it never deletes one.
function isGenerated(path: string): boolean {
  try {
    return readFileSync(path, 'utf8').includes(MARKER);
  } catch {
    return false;
  }
}

function agentFiles(agentsDir: string): string[] {
  const names = markdownNames(agentsDir);
  // bash ran without nullglob, so an agents/ with no .md left the pattern unexpanded
  // and the loop body ran once on the literal path — which then reported itself as a
  // file with no name. Kept so an empty tree reads the same through either entry.
  if (names.length === 0) return [join(agentsDir, '*.md')];
  return names.map((name) => join(agentsDir, name));
}

// The `*.md` glob's matches, in the byte order bash expanded them: no dotfiles
// (a leading `.` is never matched by `*`), and code-unit order, not the collation a
// locale-aware comparison would impose.
function markdownNames(dir: string): string[] {
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return [];
  }
  return names.filter((name) => !name.startsWith('.') && name.endsWith('.md')).sort(byCodeUnit);
}

function byCodeUnit(a: string, b: string): number {
  if (a < b) return -1;
  return a > b ? 1 : 0;
}

function isDirectory(path: string): boolean {
  try {
    return statSync(path).isDirectory();
  } catch {
    return false;
  }
}

// A file the reader cannot open has no frontmatter, which the caller reports as
// "skip (no name)" — exactly what bash's `grep ... || true` produced for it.
function readOrEmpty(path: string): string {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
}
